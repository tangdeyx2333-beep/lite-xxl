-- mod-version:4

local syntax = require "core.syntax"

syntax.add {
  name = "TypeScript with JSX",
  files = { "%.tsx$", "%.astro$" },
  comment = "//",
  block_comment = { "/*", "*/" },
  patterns = {
    -- 解析阶段：注释先处理，避免 JSX 或 TypeScript 表达式里的符号被继续高亮。
    { pattern = "//.*",                 type = "comment"  },
    { pattern = { "/%*", "%*/" },       type = "comment"  },
    -- 值阶段：TSX 中 `/` 不能直接按正则字面量处理，否则容易跨标签错误吞掉大段内容。
    { pattern = { '"', '"', '\\' },     type = "string"   },
    { pattern = { "'", "'", '\\' },     type = "string"   },
    { pattern = { "`", "`", '\\' },     type = "string"   },
    -- 值阶段：数字优先于操作符识别，避免负号和指数格式被拆散。
    { pattern = "0x[%da-fA-F]+",        type = "number"   },
    { pattern = "-?%d+[%d%.eE]*",       type = "number"   },
    { pattern = "-?%.?%d+",             type = "number"   },
    -- 结构阶段：操作符在关键字和函数前处理，保证 JSX 标签边界和表达式符号有基础高亮。
    { pattern = "[%+%-=/%*%^%%<>!~|&]", type = "operator" },
    -- 类型阶段：接口和类型别名是 TypeScript 的核心声明入口，单独标出声明名。
    { pattern = "interface%s()[%a_][%w_]*", type = {"keyword", "keyword2"} },
    { pattern = "type%s()[%a_][%w_]*", type = {"keyword", "keyword2"} },
    -- 收尾阶段：函数调用和普通符号最后识别，由 symbols 表继续细分关键字和字面量。
    { pattern = "[%a_][%w_]*%f[(]",     type = "function" },
    { pattern = "[%a_][%w_]*",          type = "symbol"   },
  },
  symbols = {
    ["async"]      = "keyword",
    ["await"]      = "keyword",
    ["break"]      = "keyword",
    ["case"]       = "keyword",
    ["catch"]      = "keyword",
    ["class"]      = "keyword",
    ["const"]      = "keyword",
    ["continue"]   = "keyword",
    ["debugger"]   = "keyword",
    ["default"]    = "keyword",
    ["delete"]     = "keyword",
    ["do"]         = "keyword",
    ["else"]       = "keyword",
    ["export"]     = "keyword",
    ["extends"]    = "keyword",
    ["finally"]    = "keyword",
    ["for"]        = "keyword",
    ["function"]   = "keyword",
    ["get"]        = "keyword",
    ["if"]         = "keyword",
    ["import"]     = "keyword",
    ["implements"] = "keyword",
    ["in"]         = "keyword",
    ["instanceof"] = "keyword",
    ["let"]        = "keyword",
    ["new"]        = "keyword",
    ["return"]     = "keyword",
    ["set"]        = "keyword",
    ["static"]     = "keyword",
    ["super"]      = "keyword",
    ["switch"]     = "keyword",
    ["throw"]      = "keyword",
    ["try"]        = "keyword",
    ["typeof"]     = "keyword",
    ["var"]        = "keyword",
    ["void"]       = "keyword",
    ["while"]      = "keyword",
    ["with"]       = "keyword",
    ["yield"]      = "keyword",
    ["true"]       = "literal",
    ["false"]      = "literal",
    ["null"]       = "literal",
    ["undefined"]  = "literal",
    ["arguments"]  = "keyword2",
    ["Infinity"]   = "keyword2",
    ["NaN"]        = "keyword2",
    ["this"]       = "keyword2",
  },
}
